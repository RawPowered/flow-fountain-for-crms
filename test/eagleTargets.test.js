const assert=require('assert/strict');
const fs=require('fs');
const path=require('path');
const {evaluateTarget,evaluateTargets,targetApplicability,normalizePeriodDays}=require('../src/services/eagleTargets');
const {SCHEMA_VERSION}=require('../src/config');

const percentMetric={metricId:'source_coverage',label:'Source attributed',unit:'percent',status:'available',value:72.7};
const off=evaluateTarget(percentMetric,{metricId:'source_coverage',targetValue:80,direction:'at_least',warningMargin:5,businessOwner:'Growth',active:1});
assert.equal(off.status,'off_target');assert.equal(off.gap,7.3);assert.equal(off.targetLabel,'≥ 80%');
const near=evaluateTarget({...percentMetric,value:76},{metricId:'source_coverage',targetValue:80,direction:'at_least',warningMargin:5,businessOwner:'Growth',active:1});
assert.equal(near.status,'near_target');
const on=evaluateTarget({metricId:'dnc_rate',label:'DNC rate',unit:'percent',status:'available',value:12},{metricId:'dnc_rate',targetValue:15,direction:'at_most',warningMargin:2,businessOwner:'Compliance',active:1});
assert.equal(on.status,'on_target');assert.equal(on.favorableVariance,3);
const unavailable=evaluateTarget({metricId:'lead_to_win_rate',label:'Lead-to-win',unit:'percent',status:'unavailable'},{metricId:'lead_to_win_rate',targetValue:10,direction:'at_least',warningMargin:2,businessOwner:'Revenue',active:1});
assert.equal(unavailable.status,'unavailable');
assert.equal(evaluateTargets({source_coverage:percentMetric},[{metricId:'source_coverage',targetValue:80,direction:'at_least',warningMargin:5,businessOwner:'Growth',active:0}]).length,0);
const scopedTarget={metricId:'source_coverage',periodDays:30,targetValue:80,direction:'at_least',warningMargin:5,businessOwner:'Growth',active:1};
assert.equal(evaluateTargets({source_coverage:percentMetric},[scopedTarget],{days:30,filters:{}})[0].status,'off_target');
const wrongPeriod=evaluateTargets({source_coverage:percentMetric},[scopedTarget],{days:7,filters:{}})[0];
assert.equal(wrongPeriod.status,'not_applicable');assert.match(wrongPeriod.applicability.reason,/last 30 days/);
const filtered=evaluateTargets({source_coverage:percentMetric},[scopedTarget],{days:30,filters:{state:'FL'}})[0];
assert.equal(filtered.status,'not_applicable');assert.match(filtered.applicability.reason,/Clear state filters/);
assert.equal(targetApplicability(scopedTarget,{days:30,filters:{}}).applicable,true);
assert.equal(normalizePeriodDays('90'),90);assert.equal(normalizePeriodDays(''),null);

const schema=fs.readFileSync(path.join(__dirname,'..','sql','schema.sql'),'utf8');
const routes=fs.readFileSync(path.join(__dirname,'..','src','routes','adminEagle.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'..','public','admin','eagle.html'),'utf8');
const client=fs.readFileSync(path.join(__dirname,'..','public','js','eagle-dashboard.js'),'utf8');
assert.ok(Number(SCHEMA_VERSION)>=32,'EAGLE target scope requires schema revision 32 or newer');
assert.match(schema,/CREATE TABLE IF NOT EXISTS eagle_metric_targets/);
assert.match(schema,/CREATE TABLE IF NOT EXISTS eagle_metric_target_audit/);
assert.match(schema,/period_days\s+SMALLINT UNSIGNED NULL/);
assert.match(fs.readFileSync(path.join(__dirname,'..','src','db','migrate.js'),'utf8'),/eagle_metric_targets', 'period_days'/);
assert.match(routes,/put\('\/api\/eagle\/targets'/);
assert.match(html,/id="view-targets"/);assert.match(html,/data-target-badge="source_coverage"/);
assert.match(html,/id="targetPeriod"/);
assert.match(client,/renderTargetBadges/);assert.match(client,/saveTarget/);
console.log('EAGLE target governance tests passed');
